// Translations. English is the default language; Swedish can be selected.
// Placeholders use {name}. Numbers are formatted by the caller with fmt().

let lang = 'en';

export const LANGS = { en: 'English', sv: 'Svenska' };

export function setLang(l) {
  lang = l === 'sv' ? 'sv' : 'en';
}

export function getLang() {
  return lang;
}

export function locale() {
  return lang === 'sv' ? 'sv-SE' : 'en-US';
}

export function t(key, params) {
  let s = STRINGS[lang][key];
  if (s === undefined) s = STRINGS.en[key];
  if (s === undefined) return key;
  if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined ? params[k] : m));
  return s;
}

// Number for display: trims trailing zeros, decimal comma and true minus in Swedish.
export function fmt(v, dec = 2) {
  const f = 10 ** dec;
  let s = String(Math.round(Number(v) * f) / f);
  if (s.includes('e')) s = Number(v).toFixed(dec);
  if (s === '-0') s = '0';
  return lang === 'sv' ? s.replace('-', '−').replace('.', ',') : s;
}

// Number for G-code: always decimal point and ASCII minus.
export function gfmt(v, dec = 3) {
  const f = 10 ** dec;
  let s = String(Math.round(Number(v) * f) / f);
  if (s === '-0') s = '0';
  return s;
}

// Integer/fixed display with thousands separators.
export function nf(v, dec = 0) {
  return Number(v).toLocaleString(locale(), { maximumFractionDigits: dec, minimumFractionDigits: dec });
}

